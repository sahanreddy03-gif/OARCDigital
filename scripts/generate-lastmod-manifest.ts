/**
 * Writes seo-manifest/lastmod.json: repo path -> date of the last commit that
 * changed it (YYYY-MM-DD, committer date). Sitemap routes read it through
 * `lastmodForPath()` in lib/seo/sitemapHelpers.ts.
 *
 * Why: Vercel builds from a shallow clone, so `git log -1 -- <path>` there
 * returns the date of the oldest commit in the clone for every page that did
 * not change recently. That made ~200 sitemap dates fake. This manifest is
 * built locally from FULL history and committed, so the build never has to
 * guess.
 *
 * Run after merging content changes (needs full history, refuses a shallow
 * clone):
 *   npm run seo:lastmod
 *
 * Semantics match `git log -1 -- <path>`: a directory's date is the newest
 * commit that touched anything under it (deletions included). Merge commits
 * are skipped, like git's default history walk for a path.
 */
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import path from "node:path";

const OUT = "seo-manifest/lastmod.json";
// Code roots: files and directories. public/: directories only (1,400+ image
// files would bloat the manifest and nothing dates a single image).
const FILE_ROOTS = ["app/", "lib/", "components/", "shared/", "seo-manifest/"];
const DIR_ONLY_ROOTS = ["public/"];
const ALL_ROOTS = [...FILE_ROOTS, ...DIR_ONLY_ROOTS];

function git(args: string[]): string {
  return execFileSync("git", args, { encoding: "utf8", maxBuffer: 1024 * 1024 * 1024 });
}

function inRoots(p: string, roots: string[]): boolean {
  return roots.some((r) => p.startsWith(r));
}

function ancestors(p: string): string[] {
  const out: string[] = [];
  let dir = path.posix.dirname(p);
  while (dir && dir !== ".") {
    out.push(dir);
    dir = path.posix.dirname(dir);
  }
  return out;
}

if (git(["rev-parse", "--is-shallow-repository"]).trim() === "true") {
  console.error("[seo:lastmod] shallow clone: run `git fetch --unshallow` first, dates would be wrong.");
  process.exit(1);
}

// Paths that exist now (tracked) and their parent directories.
const existing = new Set<string>();
for (const f of git(["ls-files", "-z"]).split("\0")) {
  if (!f || !inRoots(f, ALL_ROOTS) || f === OUT) continue;
  if (inRoots(f, FILE_ROOTS)) existing.add(f);
  for (const a of ancestors(f)) if (inRoots(`${a}/`, ALL_ROOTS)) existing.add(a);
}

// One pass over full history. --no-renames lists both sides of a rename, as
// pathspec-limited `git log -- <path>` would see them.
const log = git([
  "log",
  "--no-renames",
  "--name-only",
  "--format=@@%cd",
  "--date=short",
  "--",
  ...ALL_ROOTS,
]);

const dates: Record<string, string> = {};
let current = "";
for (const raw of log.split("\n")) {
  const line = raw.trim();
  if (!line) continue;
  if (line.startsWith("@@")) {
    current = line.slice(2);
    continue;
  }
  if (!/^\d{4}-\d{2}-\d{2}$/.test(current)) continue;
  for (const p of [line, ...ancestors(line)]) {
    if (!existing.has(p)) continue;
    if (!dates[p] || current > dates[p]) dates[p] = current;
  }
}

const sorted: Record<string, string> = {};
for (const k of Object.keys(dates).sort()) sorted[k] = dates[k];

const head = git(["rev-parse", "HEAD"]).trim();
const body = {
  _about:
    "Generated by scripts/generate-lastmod-manifest.ts (npm run seo:lastmod) from full git history. Sitemap lastmod source; do not edit by hand.",
  generatedFrom: head,
  dates: sorted,
};
writeFileSync(OUT, JSON.stringify(body, null, 2) + "\n", "utf8");
console.log(`[seo:lastmod] wrote ${Object.keys(sorted).length} paths to ${OUT} (from ${head.slice(0, 8)})`);
